local t = require("lese.testing")
local path = require("lese.builtin._path")

t.describe("builtin._path.is_absolute", function()
  t.it("accepts Unix, drive and UNC paths", function()
    t.ok(path.is_absolute("/usr/bin"))
    t.ok(path.is_absolute("C:\\Users"))
    t.ok(path.is_absolute("c:/Users"))
    t.ok(path.is_absolute("\\\\server\\share"))
  end)

  t.it("rejects relative paths", function()
    t.ok(not path.is_absolute("usr/bin"))
    t.ok(not path.is_absolute("./a"))
    t.ok(not path.is_absolute(""))
  end)
end)

t.describe("builtin._path.join", function()
  t.it("puts one separator between the parts", function()
    t.eq(path.join("/a", "b", "/"), "/a/b")
    t.eq(path.join("/", "b", "/"), "/b")
    t.eq(path.join("C:\\a\\", "b", "\\"), "C:\\a\\b")
  end)
end)

t.describe("builtin._path.strip_trailing", function()
  t.it("removes a trailing separator but keeps a root", function()
    t.eq(path.strip_trailing("/a/b/"), "/a/b")
    t.eq(path.strip_trailing("C:\\a\\"), "C:\\a")
    t.eq(path.strip_trailing("/"), "/")
    t.eq(path.strip_trailing("C:\\"), "C:\\")
  end)
end)

t.describe("builtin._path.relative", function()
  t.it("returns the part under the base", function()
    t.eq(path.relative("/a/b", "/a/b/c/d.txt", "/"), "c/d.txt")
  end)

  t.it("climbs out of the base with ..", function()
    t.eq(path.relative("/a/b", "/a/c/d.txt", "/"), "../c/d.txt")
    t.eq(path.relative("/a/b/", "/x", "/"), "../../x")
  end)

  t.it("returns . for the base itself", function()
    t.eq(path.relative("/a/b", "/a/b", "/"), ".")
  end)

  t.it("joins with the given separator and accepts either separator", function()
    t.eq(path.relative("C:\\a", "C:/a/b/c", "\\"), "b\\c")
  end)

  t.it("leaves a relative path as it is", function()
    t.eq(path.relative("/a", "b/c", "/"), "b/c")
  end)
end)

t.describe("builtin._path.replace", function()
  t.it("replaces the first occurrence literally", function()
    t.eq(path.replace("a.b:1:a.b", "a.b", "x%y"), "x%y:1:a.b")
  end)

  t.it("returns the text unchanged when the part is absent", function()
    t.eq(path.replace("abc", "z", "y"), "abc")
  end)
end)
