local t = require("lese.testing")
local host = require("lese.host")
local builtin = require("lese.builtin")

t.describe("builtin.refiner.exists", function()
  t.it("keeps items whose file exists", function()
    local p = host.fn.tempname()
    host.fn.writefile({ "x" }, p)
    local item = t.item(p, { path = p })
    t.eq(t.refine(builtin.refiner.exists(), item), item)
  end)

  t.it("keeps items whose directory exists", function()
    local p = host.fn.tempname()
    host.fn.mkdir(p, "p")
    local item = t.item(p, { path = p })
    t.eq(t.refine(builtin.refiner.exists(), item), item)
  end)

  t.it("drops items whose path does not exist", function()
    local p = host.fn.tempname()
    t.eq(t.refine(builtin.refiner.exists(), t.item(p, { path = p })), nil)
  end)
end)
