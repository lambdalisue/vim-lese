local t = require("lese.testing")
local host = require("lese.host")
local luals = require("lese.luals")

t.describe("lese.luals.library", function()
  t.it("lists the lua/ directory that holds lese's types", function()
    local dirs = luals.library()
    t.ok(#dirs >= 1)
    t.eq(host.fn.filereadable(dirs[1] .. "/lese/types.lua"), 1)
  end)

  t.it("lists the lua/ directory of a lese-* extension on 'runtimepath'", function()
    local root = host.fn.fnamemodify(host.fn.tempname(), ":p")
    host.fn.mkdir(root .. "/lua/lese-example", "p")
    local saved = host.eval("&runtimepath")
    host.cmd("let &runtimepath .= ',' . " .. host.fn.string(root))
    local dirs = luals.library()
    host.cmd("let &runtimepath = " .. host.fn.string(saved))
    t.eq(dirs[#dirs], host.fn.fnamemodify(root .. "/lua/lese-example", ":h"))
  end)

  t.it("keeps a configured library first and lists each directory once", function()
    local once = luals.library({ "/runtime" })
    t.eq(once[1], "/runtime")
    t.eq(luals.library(once), once)
  end)

  t.it("is reachable from Vim script", function()
    t.eq(host.call("lese#luals#library", { "/runtime" }), luals.library({ "/runtime" }))
    t.eq(host.call("lese#luals#library"), luals.library())
  end)
end)
